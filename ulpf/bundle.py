"""Offline (air-gap) bundle: `ulpf bundle lock|build`.

The bundle is a directory (and a .tar of it) with everything an installation
needs and nothing it must fetch:

  install.sh            installer (bash + python3 >= 3.12 stdlib); never uses the network
  verify_bundle.py      stdlib-only check of every file against BUNDLE.json
  BUNDLE.json           sha256 + size of every file, tool versions, build time
  BUNDLE.json.sig       Ed25519 signature of BUNDLE.json (release key), verifiable
                        with `openssl pkeyutl -verify -rawin` on the target
  release.pub           public key - compare its fingerprint out of band!
  src/                  the ULPF tree (code, specs, schemas, static VRL, tests, docs)
  dist/                 pinned Vector / OpenSearch / security-plugin artifacts
  wheelhouse/           every Python dependency as a wheel
  requirements.lock     exact versions + sha256 of each wheel (pip --require-hashes)

Secrets, keys, certificates, runtime data and generated configs are never
included; the installer generates them on the target.

Disk: the bundle directory hard-links the pinned binaries and wheels from
runtime/dist and runtime/wheelhouse (no extra space on the same filesystem);
`--tar` writes the single transfer file (a real ~0.5 GB copy) and removes the
directory.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import shutil
import tarfile
from pathlib import Path

from . import __version__, paths

INCLUDE_DIRS = ["ulpf", "pipeline/vector/static", "schema", "specs", "tests", "tools", "detections", "docs",
                "deploy/airgap", "scripts", "verification"]
INCLUDE_FILES = ["pyproject.toml", "README.md", "LICENSE", "THIRD_PARTY.md", "requirements.lock", "Makefile",
                 "deploy/ulpf.yaml", "deploy/keys/README.md", "deploy/certs/README.md", ".streamlit/config.toml"]
EXCLUDE_PARTS = {"__pycache__", "_drafts", ".pytest_cache"}
EXCLUDE_SUFFIX = {".pyc", ".pyo"}


def _sha(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def lock(wheelhouse: Path | None = None) -> Path:
    """requirements.lock: name==version --hash=sha256:... for every wheel."""
    from packaging.utils import parse_wheel_filename

    wh = wheelhouse or paths.RUNTIME / "wheelhouse"
    lines = ["# Generated by `ulpf bundle lock` from runtime/wheelhouse. Install with:",
             "#   pip install --no-index --find-links wheelhouse --require-hashes --only-binary=:all: -r requirements.lock"]
    for f in sorted(wh.glob("*.whl"), key=lambda p: p.name.lower()):
        name, ver, *_ = parse_wheel_filename(f.name)
        lines.append(f"{name}=={ver} --hash=sha256:{_sha(f)}")
    out = paths.HOME / "requirements.lock"
    out.write_text("\n".join(lines) + "\n")
    return out


def _source_files() -> list[Path]:
    out = []
    for d in INCLUDE_DIRS:
        root = paths.HOME / d
        if not root.exists():
            continue
        for p in sorted(root.rglob("*")):
            rel = p.relative_to(paths.HOME)
            if p.is_file() and not (set(rel.parts) & EXCLUDE_PARTS) and p.suffix not in EXCLUDE_SUFFIX:
                out.append(rel)
    for f in INCLUDE_FILES:
        if (paths.HOME / f).exists():
            out.append(Path(f))
    return out


def release_key() -> tuple[Path, Path]:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    k, pub = paths.KEYS / "release.key", paths.KEYS / "release.pub"
    if not k.exists():
        paths.KEYS.mkdir(parents=True, exist_ok=True)
        key = Ed25519PrivateKey.generate()
        fd = os.open(k, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "wb") as fh:
            fh.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
        pub.write_bytes(key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo))
    return k, pub


def _link_or_copy(src: Path, dst: Path) -> str:
    """Hard link when possible: the bundle then costs no extra disk for the
    ~500 MB of pinned binaries and wheels it shares with runtime/."""
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
        return "link"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


def build(out_dir: Path | None = None, *, tar: bool = False) -> dict:
    from cryptography.hazmat.primitives import serialization

    from . import runtime

    probs = runtime.verify(paths.RUNTIME / "dist", only_required=True)
    if probs:
        raise RuntimeError("pinned artifacts failed verification: " + "; ".join(probs))
    if not (paths.HOME / "requirements.lock").exists():
        lock()
    name = f"ulpf-bundle-{__version__}"
    root = (out_dir or paths.RUNTIME / "bundle") / name
    if root.exists():
        shutil.rmtree(root)
    (root / "src").mkdir(parents=True)
    for rel in _source_files():
        dst = root / "src" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(paths.HOME / rel, dst)
    (root / "dist").mkdir()
    modes: dict[str, int] = {}
    for a in runtime.load_pins():
        f = paths.RUNTIME / "dist" / a.file
        if f.exists():
            m = _link_or_copy(f, root / "dist" / a.file)
            modes[m] = modes.get(m, 0) + 1
    for w in sorted((paths.RUNTIME / "wheelhouse").glob("*.whl")):
        m = _link_or_copy(w, root / "wheelhouse" / w.name)
        modes[m] = modes.get(m, 0) + 1
    shutil.copy2(paths.HOME / "requirements.lock", root / "requirements.lock")
    for f in ("install.sh", "verify_bundle.py"):
        shutil.copy2(paths.DEPLOY / "airgap" / f, root / f)
    (root / "install.sh").chmod(0o755)
    k, pub = release_key()
    shutil.copy2(pub, root / "release.pub")
    files = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and p.name not in ("BUNDLE.json", "BUNDLE.json.sig"):
            files[str(p.relative_to(root))] = {"sha256": _sha(p), "bytes": p.stat().st_size}
    from . import vector

    manifest = {"format": "ulpf-bundle/1", "ulpf": __version__, "built_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                "vector": vector.version(), "ocsf": paths.OCSF_VERSION, "files": files,
                "total_bytes": sum(f["bytes"] for f in files.values())}
    body = json.dumps(manifest, indent=1, sort_keys=True).encode() + b"\n"
    (root / "BUNDLE.json").write_bytes(body)
    key = serialization.load_pem_private_key(k.read_bytes(), password=None)
    (root / "BUNDLE.json.sig").write_bytes(key.sign(body))
    rep = {"bundle_dir": str(root), "files": len(files), "bytes": manifest["total_bytes"], "large_files": modes,
           "manifest_sha256": hashlib.sha256(body).hexdigest(),
           "release_pub_sha256": hashlib.sha256(pub.read_bytes()).hexdigest()}
    if tar:
        t = root.parent / f"{name}.tar"
        with tarfile.open(t, "w") as tf:
            tf.add(root, arcname=name)
        rep["tar"] = str(t)
        rep["tar_sha256"] = _sha(t)
        rep["tar_bytes"] = t.stat().st_size
        shutil.rmtree(root)          # the .tar is the deliverable; keep disk usage down
        rep["bundle_dir"] = None
    return rep
